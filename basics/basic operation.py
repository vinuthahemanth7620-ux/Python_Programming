# Write a program to accept two numbers from the user and 
# display their sum, difference, product, quotient and remainder.
num1= int(input("enter the first number:"))
num2= int(input("enter the second number:"))
print("sum of two numbers:", num1+num2)
print("Difference of two numbers:", num1 -num2)
print("product of two numbers:", num1 *num2)
print("Quotient of two numbers:", num1 / num2)
print("Remainder of two numbers:", num1 % num2)